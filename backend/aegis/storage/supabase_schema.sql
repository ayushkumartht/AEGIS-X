-- AEGIS-X schema for Supabase (PostgreSQL).
-- Paste into Supabase -> SQL Editor -> Run. Safe to run more than once.
-- Same tables and column names as the SQLite schema in db.py, with Postgres types.
-- Row Level Security is on with no policies: the public anon key can read or write nothing.
-- Only the backend, connecting with the database password, can use these tables.

-- 1. Saved plans (baseline, edited, optimiser options)
create table if not exists plan (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  district    text not null,
  origin      text not null,
  plan_json   jsonb not null
);

-- 2. Simulation runs: the plan, the forecast used and the outcome summary
create table if not exists run (
  id             bigint generated by default as identity primary key,
  created_at     timestamptz not null default now(),
  district       text not null,
  plan_json      jsonb not null,
  n_samples      integer not null,
  seed           integer,
  forecast_json  jsonb not null,
  summary_json   jsonb not null
);
create index if not exists run_district_created on run (district, created_at desc);

-- 3. Field reports ("bridge_main closed") and what was parsed from them
create table if not exists field_report (
  id           bigint generated by default as identity primary key,
  received_at  timestamptz not null default now(),
  district     text not null,
  source_type  text not null,
  raw_text     text not null,
  parsed_json  jsonb not null,
  author       text not null default ''
);
create index if not exists field_report_district on field_report (district, received_at desc);

-- 4. Decision log: who accepted / edited / rejected which plan, with evidence and hash chain
create table if not exists decision (
  id             bigint generated by default as identity primary key,
  decided_at     timestamptz not null default now(),
  district       text not null,
  author         text not null,
  action         text not null check (action in ('accept', 'edit', 'reject')),
  plan_json      jsonb not null,
  run_id         bigint references run (id),
  explanation    text not null,
  note           text not null,
  evidence_json  jsonb not null default '{}'::jsonb,
  previous_hash  text,
  decision_hash  text
);
create index if not exists decision_district on decision (district, id desc);

-- The decision log is append-only: rows can be added, never changed or removed.
create or replace function decision_append_only() returns trigger language plpgsql as $$
begin
  raise exception 'decision log is append-only (% blocked)', tg_op;
end $$;
drop trigger if exists decision_no_change on decision;
create trigger decision_no_change before update or delete on decision
  for each row execute function decision_append_only();

-- 5. Official alerts (NDMA SACHET, GDACS), one row per alert
create table if not exists ops_event (
  uid           text primary key,
  source        text not null,
  hazard        text not null,
  event         text not null,
  severity      text not null,
  urgency       text not null,
  certainty     text not null,
  sender        text not null,
  state         text not null,
  area          text not null,
  headline      text not null,
  description   text not null,
  lat           double precision,
  lon           double precision,
  place_method  text not null,
  district_id   text,
  effective     timestamptz,
  expires       timestamptz,
  sent          timestamptz not null,
  gauge_json    jsonb,
  url           text not null,
  fetched_at    timestamptz not null default now()
);
create index if not exists ops_event_sent on ops_event (sent);
create index if not exists ops_event_district on ops_event (district_id);

-- 6. River risk per district over time (GloFAS ensemble vs return periods)
create table if not exists ops_indicator (
  id           bigint generated by default as identity primary key,
  district_id  text not null,
  computed_at  timestamptz not null default now(),
  level        text not null check (level in ('normal', 'watch', 'warning', 'severe', 'unknown')),
  data_json    jsonb not null
);
create index if not exists ops_indicator_district on ops_indicator (district_id, id);

-- 7. Feed health: last attempt, last success, last error per data feed
create table if not exists ops_feed (
  name          text primary key,
  last_attempt  timestamptz,
  last_success  timestamptz,
  last_error    text,
  items         integer not null default 0
);

-- 8. AI / rule-based briefs with the evidence they cite
create table if not exists ops_brief (
  id             bigint generated by default as identity primary key,
  created_at     timestamptz not null default now(),
  mode           text not null,
  author         text not null,
  source         text not null,
  model          text not null,
  evidence_json  jsonb not null,
  sections_json  jsonb not null
);

-- 9. Recommendations inside a brief, and the officer's accept / reject
create table if not exists ops_recommendation (
  id           bigint generated by default as identity primary key,
  brief_id     bigint not null references ops_brief (id) on delete cascade,
  district_id  text,
  action       text not null,
  detail_json  jsonb not null,
  status       text not null default 'proposed' check (status in ('proposed', 'accepted', 'rejected')),
  decided_by   text,
  decided_at   timestamptz,
  decision_id  bigint references decision (id)
);
create index if not exists ops_recommendation_brief on ops_recommendation (brief_id);

-- Lock every table to the backend only (no policies = no access through the anon key).
alter table plan               enable row level security;
alter table run                enable row level security;
alter table field_report       enable row level security;
alter table decision           enable row level security;
alter table ops_event          enable row level security;
alter table ops_indicator      enable row level security;
alter table ops_feed           enable row level security;
alter table ops_brief          enable row level security;
alter table ops_recommendation enable row level security;

-- Handy view for the Supabase dashboard: the latest flood level of each district.
create or replace view ops_latest_level with (security_invoker = true) as
select distinct on (district_id) district_id, level, computed_at
from ops_indicator
order by district_id, id desc;
